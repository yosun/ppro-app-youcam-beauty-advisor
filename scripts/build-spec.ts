// Generates the machine-readable standard into spec/ from the code:
//
//   spec/openapi.yaml                    the HTTP API (OpenAPI 3.1)
//   spec/schemas/manifest.schema.json    what a ppro-app publishes
//   spec/schemas/session.schema.json     the session snapshot
//   spec/schemas/event.schema.json       every event, as one oneOf
//   spec/schemas/tool-response.schema.json
//   spec/schemas/tools/<name>.json       one tool's arguments
//   spec/manifest.example.json           this app's live manifest
//
//   npm run spec:build     write the files
//   npm run spec:check     fail if the committed files are out of date (CI)

import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { z } from "zod";
import { beautyAdvisor } from "../src/advisor/app.ts";
import { PROTOCOL } from "../src/protocol/constants.ts";
import { buildManifest } from "../src/protocol/manifest.ts";
import { manifestSchema } from "../src/protocol/manifest-schema.ts";
import { buildOpenApi } from "../src/protocol/openapi.ts";
import * as schemas from "../src/protocol/schemas.ts";
import { EVENT_TYPES } from "../src/protocol/types.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const spec = join(root, "spec");

const SCHEMA_DIALECT = "https://json-schema.org/draft/2020-12/schema";
// Schema ids are the URLs the files are served from, so validators can fetch
// them by id.
const ID_BASE =
  "https://raw.githubusercontent.com/yosun/ppro-app-youcam-beauty-advisor/main/spec/schemas";

function schemaOf(name: string, title: string, schema: z.ZodType) {
  const json = z.toJSONSchema(schema, {
    target: "draft-2020-12",
    io: "output",
    unrepresentable: "any",
  }) as Record<string, unknown>;
  delete json.$schema;
  return {
    $schema: SCHEMA_DIALECT,
    $id: `${ID_BASE}/${name}.schema.json`,
    title,
    ...json,
  };
}

/**
 * A small YAML writer: enough for OpenAPI (maps, lists, scalars). A string is
 * written bare only when YAML cannot read it as anything else; every other
 * string is JSON-quoted (JSON strings are valid YAML). In particular a leading
 * "#" starts a comment, so "#/components/..." references must be quoted.
 */
export function yaml(value: unknown, indent = 0): string {
  const pad = "  ".repeat(indent);
  const scalar = (item: unknown): string => {
    if (item === null) return "null";
    if (typeof item === "number" || typeof item === "boolean")
      return String(item);
    const text = String(item);
    const plain =
      /^[A-Za-z][A-Za-z0-9_ ./()-]*$/.test(text) &&
      !text.endsWith(" ") &&
      !/^(true|false|null|yes|no|on|off|y|n|~)$/i.test(text);
    return plain ? text : JSON.stringify(text);
  };
  if (Array.isArray(value)) {
    if (!value.length) return "[]";
    return value
      .map((item) => {
        if (item && typeof item === "object") {
          const body = yaml(item, indent + 1);
          return `${pad}- ${body.trimStart()}`;
        }
        return `${pad}- ${scalar(item)}`;
      })
      .join("\n");
  }
  if (value && typeof value === "object") {
    const entries = Object.entries(value as Record<string, unknown>).filter(
      ([, item]) => item !== undefined,
    );
    if (!entries.length) return "{}";
    return entries
      .map(([key, item]) => {
        const name = /^[A-Za-z_][A-Za-z0-9_-]*$/.test(key)
          ? key
          : JSON.stringify(key);
        if (item && typeof item === "object") {
          const empty = Array.isArray(item)
            ? !item.length
            : !Object.keys(item).length;
          if (empty)
            return `${pad}${name}: ${Array.isArray(item) ? "[]" : "{}"}`;
          return `${pad}${name}:\n${yaml(item, indent + 1)}`;
        }
        if (typeof item === "string" && item.includes("\n"))
          return `${pad}${name}: |-\n${item
            .split("\n")
            .map((line) => `${pad}  ${line}`.replace(/\s+$/, ""))
            .join("\n")}`;
        return `${pad}${name}: ${scalar(item)}`;
      })
      .join("\n");
  }
  return scalar(value);
}

export async function buildFiles(): Promise<Map<string, string>> {
  const files = new Map<string, string>();
  const json = (value: unknown) => `${JSON.stringify(value, null, 2)}\n`;

  files.set(
    "openapi.yaml",
    `# Generated by \`npm run spec:build\` from the code. Do not edit by hand.\n${yaml(buildOpenApi(beautyAdvisor))}\n`,
  );

  files.set(
    "schemas/manifest.schema.json",
    json(schemaOf("manifest", "PPRO App manifest", manifestSchema)),
  );
  files.set(
    "schemas/session.schema.json",
    json(schemaOf("session", "PPRO App session snapshot", schemas.session)),
  );
  files.set(
    "schemas/tool-response.schema.json",
    json(
      schemaOf("tool-response", "PPRO App tool response", schemas.toolResponse),
    ),
  );
  files.set(
    "schemas/event.schema.json",
    json(
      schemaOf(
        "event",
        "PPRO App event",
        z.union(
          Object.values(schemas.eventSchemas) as [
            z.ZodType,
            z.ZodType,
            ...z.ZodType[],
          ],
        ),
      ),
    ),
  );
  files.set(
    "schemas/requests.schema.json",
    json({
      $schema: SCHEMA_DIALECT,
      $id: `${ID_BASE}/requests.schema.json`,
      title: "PPRO App request bodies",
      $defs: {
        createSession: schemaOf(
          "create-session",
          "Create a session",
          schemas.createSessionBody,
        ),
        message: schemaOf("message", "Send a message", schemas.messageBody),
        consent: schemaOf("consent", "Record consent", schemas.consentBody),
        presence: schemaOf("presence", "Set presence", schemas.presenceBody),
        uiEvent: schemaOf(
          "ui-event",
          "Report a client UI event",
          schemas.uiEventBody,
        ),
      },
    }),
  );

  const manifest = buildManifest(beautyAdvisor, {
    engine: "simulated",
    mcp: true,
    standalone: false,
    embedding: true,
  });
  for (const tool of manifest.tools)
    files.set(
      `schemas/tools/${tool.name}.json`,
      json({
        $schema: SCHEMA_DIALECT,
        $id: `${ID_BASE}/tools/${tool.name}.json`,
        title: `${tool.title} (${tool.name}) arguments`,
        description: tool.description,
        ...tool.inputSchema,
      }),
    );
  files.set("manifest.example.json", json(manifest));
  files.set(
    "README.md",
    `# Specification files

Generated from the code by \`npm run spec:build\`; \`npm run spec:check\` fails CI
if they are stale. Do not edit them by hand. The prose standard is
[docs/PPRO-APP-API.md](../docs/PPRO-APP-API.md).

| File | What it is |
| --- | --- |
| \`openapi.yaml\` | The HTTP API, OpenAPI 3.1. |
| \`schemas/manifest.schema.json\` | What a ppro-app publishes at \`/.well-known/ppro-app.json\`. Validate any app's manifest against it. |
| \`schemas/session.schema.json\` | The session snapshot. |
| \`schemas/event.schema.json\` | Every event, as a \`oneOf\`. |
| \`schemas/tool-response.schema.json\` | What a tool call returns. |
| \`schemas/requests.schema.json\` | The request bodies. |
| \`schemas/tools/<name>.json\` | One tool's arguments (${manifest.tools.length} tools). |
| \`manifest.example.json\` | This app's manifest, as a worked example. |

Protocol identifier: \`${PROTOCOL}\`. ${EVENT_TYPES.length} event types.
`,
  );
  return files;
}

async function listFiles(dir: string): Promise<string[]> {
  const out: string[] = [];
  for (const entry of await readdir(dir, { withFileTypes: true }).catch(
    () => [],
  )) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await listFiles(path)));
    else out.push(path);
  }
  return out;
}

async function main() {
  const check = process.argv.includes("--check");
  const files = await buildFiles();
  if (check) {
    const problems: string[] = [];
    for (const [name, content] of files) {
      const current = await readFile(join(spec, name), "utf8").catch(
        () => null,
      );
      if (current === null) problems.push(`missing    spec/${name}`);
      else if (current !== content) problems.push(`out of date spec/${name}`);
    }
    const expected = new Set([...files.keys()].map((name) => join(spec, name)));
    for (const path of await listFiles(spec))
      if (!expected.has(path))
        problems.push(`stale      spec/${relative(spec, path)}`);
    if (problems.length) {
      console.error(
        `The specification files do not match the code:\n  ${problems.join("\n  ")}\nRun \`npm run spec:build\` and commit the result.`,
      );
      process.exit(1);
    }
    console.log(`spec/ is up to date (${files.size} files).`);
    return;
  }
  await rm(spec, { recursive: true, force: true });
  for (const [name, content] of files) {
    const path = join(spec, name);
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, content);
  }
  console.log(`Wrote ${files.size} files to spec/.`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href)
  await main();
